/// Whether a chunk upload created a chunk or found it already stored.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PutOutcome {
    /// The chunk is new; the response is `201`.
    Created,
    /// The chunk was already stored; the response is `200`.
    Existed,
}

/// What appending a version did.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct AppendOutcome {
    /// The journal position of the version.
    pub seq: Seq,
    /// The file's heads afterwards.
    pub heads: Vec<VersionId>,
    /// Whether the file conflicts afterwards.
    pub conflicted: bool,
    /// Whether this version was already stored (an idempotent repost).
    pub existed: bool,
}

/// Every way the storage engine refuses or fails.
///
/// Each variant carries the numbers the refusal was decided on, so the log
/// line and the HTTP body can both state them (AGENTS.md requirement 12).
#[derive(Debug)]
pub enum StoreError {
    /// The body did not hash to the sid it was stored under.
    SidMismatch {
        /// The sid the client asked for.
        expected: Sid,
        /// The sid the body actually hashes to.
        actual: Sid,
    },
    /// The body length did not match `Content-Length`.
    LengthMismatch {
        /// What the client declared.
        declared: u64,
        /// What arrived.
        actual: u64,
    },
    /// Free space is at or below the watermark.
    VolumeFull {
        /// Bytes free after this write would land.
        free: u64,
        /// The refusal threshold.
        watermark: u64,
    },
    /// The account quota is exhausted.
    QuotaExceeded {
        /// Bytes used after this write would land.
        used: u64,
        /// The quota.
        quota: u64,
    },
    /// A version referenced chunks the server does not hold.
    MissingChunks(Vec<Sid>),
    /// The posted version id is not the server's recomputation.
    VersionIdMismatch {
        /// What the server computed.
        expected: VersionId,
        /// What the client posted.
        actual: VersionId,
    },
    /// A feed cursor beyond the journal head.
    SeqAhead {
        /// What the client asked for.
        requested: Seq,
        /// The journal head.
        head: Seq,
    },
    /// No such device.
    UnknownDevice,
    /// The device is revoked.
    DeviceRevoked,
    /// The device claimed a pairing but nobody has approved it.
    DevicePending,
    /// No such file.
    UnknownFile,
    /// No such domain: no file the store holds is in it.
    UnknownDomain,
    /// A version named a domain other than its file's own.
    DomainMismatch {
        /// The domain the file's first version fixed.
        expected: DomainId,
        /// What this version named.
        actual: DomainId,
    },
    /// No such version.
    UnknownVersion,
    /// Setup has not run.
    NotSetUp,
    /// Setup has already run.
    AlreadySetUp,
    /// The filesystem refused.
    Io(io::Error),
    /// A volume root or credential file whose type, owner, or mode is not
    /// safe to serve from, and could not be corrected.
    Posture {
        /// Which class of path, matching the refusal line's `path_class`.
        class: &'static str,
        /// Why it was refused, matching the refusal line's `reason`.
        reason: &'static str,
    },
    /// On-disk state that replay cannot make sense of.
    Corrupt(String),
}

impl fmt::Display for StoreError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            StoreError::SidMismatch { expected, actual } => {
                write!(
                    f,
                    "sid mismatch: expected {expected}, body hashes to {actual}"
                )
            }
            StoreError::LengthMismatch { declared, actual } => {
                write!(f, "length mismatch: declared {declared}, received {actual}")
            }
            StoreError::VolumeFull { free, watermark } => {
                write!(f, "volume full: {free} bytes free, watermark {watermark}")
            }
            StoreError::QuotaExceeded { used, quota } => {
                write!(f, "quota exceeded: {used} bytes used, quota {quota}")
            }
            StoreError::MissingChunks(sids) => write!(f, "missing {} chunks", sids.len()),
            StoreError::VersionIdMismatch { expected, actual } => {
                write!(
                    f,
                    "version id mismatch: expected {expected}, posted {actual}"
                )
            }
            StoreError::SeqAhead { requested, head } => {
                write!(f, "seq {requested} is ahead of head {head}")
            }
            StoreError::UnknownDevice => f.write_str("unknown device"),
            StoreError::DeviceRevoked => f.write_str("device revoked"),
            StoreError::DevicePending => f.write_str("device pending approval"),
            StoreError::UnknownFile => f.write_str("unknown file"),
            StoreError::UnknownDomain => f.write_str("unknown domain"),
            StoreError::DomainMismatch { expected, actual } => {
                write!(
                    f,
                    "domain mismatch: file is in {expected}, version named {actual}"
                )
            }
            StoreError::UnknownVersion => f.write_str("unknown version"),
            StoreError::NotSetUp => f.write_str("not set up"),
            StoreError::AlreadySetUp => f.write_str("already set up"),
            StoreError::Io(e) => write!(f, "io error: {:?}", e.kind()),
            StoreError::Posture { class, reason } => {
                write!(f, "unsafe posture on the {class}: {reason}")
            }
            StoreError::Corrupt(what) => write!(f, "corrupt on-disk state: {what}"),
        }
    }
}

impl std::error::Error for StoreError {}

impl From<io::Error> for StoreError {
    fn from(e: io::Error) -> StoreError {
        StoreError::Io(e)
    }
}

impl StoreError {
    /// The snake_case refusal code for this error (`docs/protocol.md`).
    ///
    /// A `&'static str`, so it can be logged without carrying runtime data.
    pub const fn code(&self) -> &'static str {
        match self {
            StoreError::SidMismatch { .. } => "sid_mismatch",
            StoreError::LengthMismatch { .. } => "length_mismatch",
            StoreError::VolumeFull { .. } => "volume_full",
            StoreError::QuotaExceeded { .. } => "quota_exceeded",
            StoreError::MissingChunks(_) => "missing_chunks",
            StoreError::VersionIdMismatch { .. } => "version_id_mismatch",
            StoreError::SeqAhead { .. } => "seq_ahead",
            StoreError::UnknownDevice => "unknown_device",
            StoreError::DeviceRevoked => "device_revoked",
            StoreError::DevicePending => "device_pending",
            StoreError::UnknownFile => "unknown_file",
            StoreError::UnknownDomain => "unknown_domain",
            StoreError::DomainMismatch { .. } => "domain_mismatch",
            StoreError::UnknownVersion => "unknown_version",
            StoreError::NotSetUp => "not_set_up",
            StoreError::AlreadySetUp => "already_set_up",
            StoreError::Io(_) => "io_error",
            StoreError::Posture { .. } => "unsafe_posture",
            StoreError::Corrupt(_) => "corrupt",
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn refusals_state_their_numbers_and_a_stable_code() {
        let err = StoreError::VolumeFull {
            free: 7,
            watermark: 2048,
        };
        assert_eq!(err.to_string(), "volume full: 7 bytes free, watermark 2048");
        assert_eq!(err.code(), "volume_full");

        let err = StoreError::QuotaExceeded { used: 10, quota: 5 };
        assert_eq!(err.to_string(), "quota exceeded: 10 bytes used, quota 5");
        assert_eq!(err.code(), "quota_exceeded");

        let err = StoreError::LengthMismatch {
            declared: 4,
            actual: 5,
        };
        assert_eq!(err.to_string(), "length mismatch: declared 4, received 5");
        assert_eq!(err.code(), "length_mismatch");

        let err = StoreError::SeqAhead {
            requested: Seq(9),
            head: Seq(3),
        };
        assert_eq!(err.to_string(), "seq 9 is ahead of head 3");
        assert_eq!(err.code(), "seq_ahead");

        // A posture refusal states the class and the reason, both compile
        // time words, and no location.
        let err = StoreError::Posture {
            class: "server_key",
            reason: "symlink",
        };
        assert_eq!(err.to_string(), "unsafe posture on the server_key: symlink");
        assert_eq!(err.code(), "unsafe_posture");
    }

    #[test]
    fn io_errors_never_render_their_message() {
        let err = StoreError::from(io::Error::new(
            io::ErrorKind::PermissionDenied,
            "/data/blobs/v1/aa/bb/secret",
        ));
        let text = err.to_string();
        assert!(!text.contains("/data"), "{text}");
        assert_eq!(text, "io error: PermissionDenied");
        assert_eq!(err.code(), "io_error");
    }

    #[test]
    fn device_states_round_trip_their_wire_words() {
        for state in [
            DeviceState::Pending,
            DeviceState::Active,
            DeviceState::Revoked,
        ] {
            assert_eq!(DeviceState::parse(state.as_word()), Some(state));
        }
        assert_eq!(DeviceState::parse("approved"), None);
        assert_eq!(DeviceState::parse(""), None);
    }

    #[test]
    fn seen_kinds_round_trip_their_wire_words() {
        for kind in [SeenKind::SignIn, SeenKind::Edit, SeenKind::Heartbeat] {
            assert_eq!(SeenKind::parse(kind.as_word()), Some(kind));
        }
        assert_eq!(SeenKind::parse("deleted"), None);
    }
}
