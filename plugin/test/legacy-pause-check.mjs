import { strict as assert } from 'node:assert';
import { createRequire } from 'node:module';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
const legacy = resolve(process.argv[2] ?? '');
if (!process.argv[2]) throw new Error('usage: node plugin/test/legacy-pause-check.mjs <built legacy plugin directory>');
const { rig, FakeTimers } = await import(pathToFileURL(join(legacy, 'test/fake.mjs')));
const require = createRequire(join(legacy, 'test/check.mjs'));
const { SyncEngine } = require('../build/sync/engine.js');
const r = await rig(), timers = new FakeTimers();
const target = 'ab'.repeat(16), control = 'ac'.repeat(16), peer = 'ff'.repeat(16);
const held = await r.server.publishManifest({ fileId: control, manifest: {v:3,kind:'pause',path:'Notes/held.md',target,paused:true,domain:r.context.domainId,size:0,chunks:[],sha256:'',deleted:false}, sids:[],parents:[],deviceId:peer,manifestKey:r.keys.manifestKey,bytes:0 });
const later = await r.server.publish({fileId:target,path:'Notes/after.md',bytes:new TextEncoder().encode('later frame reached the old client\n'),mtime:r.host.clock,parents:[],domainKey:r.keys.domainKey,manifestKey:r.keys.manifestKey,deviceId:peer});
const engine = new SyncEngine({...r,timers,now:()=>r.host.clock});
await engine.start();
await timers.run(50,()=>r.host.text('Notes/after.md')!==null && r.state.data.lastSeq>=later.seq);
assert.equal(r.host.text('Notes/held.md'),null);
assert.equal(r.host.text('Notes/after.md'),'later frame reached the old client\n');
assert.ok(r.host.logs.some(line=>line.includes('decision=refused reason=version') && line.includes(control)));
assert.ok(r.state.data.lastSeq>=later.seq);
engine.stop(); r.server.releaseFeed(); await engine.stopAndWait();
console.log(JSON.stringify({client:'1.1.1',controlSequence:held.seq,laterSequence:later.seq,cursor:r.state.data.lastSeq,unsupportedControl:'refused',followingNote:'applied',feed:'advanced'}));
